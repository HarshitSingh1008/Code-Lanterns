function hash(seed: string) {
  let h = 0x811c9dc5;
  for (let i = 0; i < seed.length; i += 1) {
    h ^= seed.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h.toString(16).padStart(8, '0');
}

function audit(
  id: string,
  minutesAgo: number,
  actor: string,
  action: string,
  target: string,
  category: AuditEntry['category'],
  ok = true
): AuditEntry {
  return { id, at: now - minutesAgo * 60_000, actor, action, target, category, hash: hash(id), ok };
}

